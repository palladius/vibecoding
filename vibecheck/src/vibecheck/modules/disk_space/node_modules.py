def run(console, config, verbose, cached_data=None):
    """
    The main function for the node_modules check.
    """
    if verbose:
        console.print("[bold green]Running node_modules check...[/bold green]")

    if cached_data:
        if verbose:
            console.print("✅ Using cached data.")
        all_dirs = cached_data["data"]
        total_size = sum(d['size'] for d in all_dirs)
    else:
        start_path = Path.home() / "git" # As per the spec
        node_modules_dirs = find_node_modules(start_path)

        if not node_modules_dirs:
            if verbose:
                console.print("No node_modules directories found. ✨")
            return {"summary": "No node_modules found."}

        total_size = 0
        all_dirs = []
        for dir_path in node_modules_dirs:
            size = get_dir_size(dir_path)
            total_size += size
            all_dirs.append({"path": str(dir_path), "size": size})

    summary = f"Found {len(all_dirs)} node_modules directories, total size: [bold yellow]{total_size / 1024 / 1024:.2f} MB[/bold yellow]"

    if verbose:
        table = Table(title="Node Modules Analysis")
        table.add_column("Path", justify="left", style="cyan", no_wrap=False, max_width=80)
        table.add_column("Size", justify="right", style="magenta")

        # Sort by size for verbose output
        sorted_dirs = sorted(all_dirs, key=lambda d: d['size'], reverse=True)

        for dir_info in sorted_dirs:
            table.add_row(dir_info["path"], f"{dir_info['size'] / 1024 / 1024:.2f} MB")

        console.print(table)
        console.print(f"Total size of all node_modules: [bold yellow]{total_size / 1024 / 1024:.2f} MB[/bold yellow]")

    return {"summary": summary, "data": all_dirs}
